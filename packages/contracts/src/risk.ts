import { z } from 'zod';
const uuid = z.string().uuid().toLowerCase();
const version = z.number().int().positive();
const time = z.iso.datetime();
export const RiskReportStatusSchema = z.enum(['OPEN', 'INVESTIGATING', 'ACTIONED', 'DISMISSED']);
export const RiskCommandResultSchema = z.strictObject({ resourceId: uuid, version });
export type RiskCommandResult = z.infer<typeof RiskCommandResultSchema>;
export const RiskTargetTypeSchema = z.enum(['ITEM', 'SHIPMENT', 'ORDER']);
export const RiskReasonSchema = z.enum(['PROHIBITED_ITEM', 'FALSE_SHIPMENT', 'FRAUDULENT_TRADE', 'OTHER']);
export const TradingRestrictionStatusSchema = z.enum(['CLEAR', 'FROZEN']);
export const RiskTaskStatusSchema = z.enum(['OPEN', 'INVESTIGATING', 'RESOLVED']);
const report = { targetType: RiskTargetTypeSchema, targetId: uuid, reason: RiskReasonSchema, description: z.string().trim().min(1).max(2000) };
export const CreateRiskReportSchema = z.strictObject({ ...report, expectedTargetVersion: version });
export const RiskReportViewSchema = z.strictObject({ id: uuid, ...report, status: RiskReportStatusSchema, version, createdAt: time, updatedAt: time });
export const AdminRiskReportViewSchema = RiskReportViewSchema;
export const RiskReportListViewSchema = z.strictObject({ items: z.array(RiskReportViewSchema), nextCursor: z.string().nullable() });
export const TradingRestrictionViewSchema = z.strictObject({ status: TradingRestrictionStatusSchema, version, reason: z.string().nullable() });
export type RiskReportStatus = z.infer<typeof RiskReportStatusSchema>;
export type RiskTargetType = z.infer<typeof RiskTargetTypeSchema>;
export type RiskReason = z.infer<typeof RiskReasonSchema>;
export type TradingRestrictionStatus = z.infer<typeof TradingRestrictionStatusSchema>;
export type RiskTaskStatus = z.infer<typeof RiskTaskStatusSchema>;
export type CreateRiskReportInput = z.infer<typeof CreateRiskReportSchema>;
export type RiskReportView = z.infer<typeof RiskReportViewSchema>;
export type AdminRiskReportView = z.infer<typeof AdminRiskReportViewSchema>;
export type RiskReportListView = z.infer<typeof RiskReportListViewSchema>;
export type TradingRestrictionView = z.infer<typeof TradingRestrictionViewSchema>;
